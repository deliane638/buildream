-- BUILDREAM SARL — migration adaptée aux tables françaises déjà présentes.
-- Ce script NE supprime aucune table et NE supprime aucune donnée.
-- Il ajoute uniquement les champs manquants nécessaires et la table des demandes.
-- À exécuter dans Supabase > SQL Editor > New query, après sauvegarde du projet.

create extension if not exists pgcrypto;

-- 1) Compléter les tables existantes sans les remplacer.
alter table public.secteurs
  add column if not exists visible boolean not null default true;

alter table public.profil
  add column if not exists "nom et prénom" text,
  add column if not exists "rôle" text not null default 'client',
  add column if not exists "créer_à" timestamptz not null default now();

-- La table matériels existe déjà avec ses colonnes françaises.
-- On ne change ni son identifiant, ni sa clé étrangère secteur_id.
-- On ajoute seulement une date de création facultative si elle n'existe pas.
alter table public."matériels"
  add column if not exists "créer_à" timestamptz not null default now();

-- 2) Table des messages envoyés depuis le formulaire de contact.
create table if not exists public.demandes_contact (
  identifiant bigint generated by default as identity primary key,
  nom text not null,
  email text not null,
  objet text not null,
  message text not null,
  statut text not null default 'nouvelle',
  cree_a timestamptz not null default now()
);

-- 3) Rôle du membre connecté. SECURITY DEFINER évite la récursion RLS sur profil.
create or replace function public.buildream_role_connecte()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select p."rôle"
  from public.profil as p
  where p.identifiant = auth.uid()
  limit 1
$$;

-- 4) Créer automatiquement le profil client à l'inscription.
create or replace function public.buildream_creer_profil()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profil (identifiant, "nom et prénom", "rôle", "créer_à")
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    'client',
    now()
  )
  on conflict (identifiant) do nothing;
  return new;
end;
$$;

drop trigger if exists buildream_auth_user_created on auth.users;
create trigger buildream_auth_user_created
after insert on auth.users
for each row execute procedure public.buildream_creer_profil();

-- 5) Activer la sécurité au niveau des lignes.
alter table public.profil enable row level security;
alter table public.secteurs enable row level security;
alter table public."matériels" enable row level security;
alter table public.demandes_contact enable row level security;

-- 6) Profils : lecture de son propre profil; l'admin peut lire et gérer les profils.
drop policy if exists "buildream profil lire soi ou admin" on public.profil;
create policy "buildream profil lire soi ou admin"
on public.profil for select to authenticated
using (
  identifiant = auth.uid()
  or public.buildream_role_connecte() = 'admin'
);

drop policy if exists "buildream profil modifier son nom" on public.profil;
create policy "buildream profil modifier son nom"
on public.profil for update to authenticated
using (identifiant = auth.uid())
with check (
  identifiant = auth.uid()
  and "rôle" = public.buildream_role_connecte()
);

drop policy if exists "buildream admin gerer profils" on public.profil;
create policy "buildream admin gerer profils"
on public.profil for all to authenticated
using (public.buildream_role_connecte() = 'admin')
with check (public.buildream_role_connecte() = 'admin');

-- 7) Secteurs : visibles publiquement; admin et staff peuvent les gérer.
drop policy if exists "buildream secteurs lecture publique" on public.secteurs;
create policy "buildream secteurs lecture publique"
on public.secteurs for select to anon, authenticated
using (visible = true or public.buildream_role_connecte() in ('admin','staff'));

drop policy if exists "buildream equipe gerer secteurs" on public.secteurs;
create policy "buildream equipe gerer secteurs"
on public.secteurs for all to authenticated
using (public.buildream_role_connecte() in ('admin','staff'))
with check (public.buildream_role_connecte() in ('admin','staff'));

-- 8) Matériels : lecture publique; admin et staff peuvent gérer le catalogue.
drop policy if exists "buildream materiels lecture publique" on public."matériels";
create policy "buildream materiels lecture publique"
on public."matériels" for select to anon, authenticated
using (
  disponible = true
  or public.buildream_role_connecte() in ('admin','staff')
);

drop policy if exists "buildream equipe gerer materiels" on public."matériels";
create policy "buildream equipe gerer materiels"
on public."matériels" for all to authenticated
using (public.buildream_role_connecte() in ('admin','staff'))
with check (public.buildream_role_connecte() in ('admin','staff'));

-- 9) Demandes : tout visiteur peut envoyer une demande; seule l'équipe peut les lire/traiter.
drop policy if exists "buildream public envoyer demande" on public.demandes_contact;
create policy "buildream public envoyer demande"
on public.demandes_contact for insert to anon, authenticated
with check (
  length(nom) between 1 and 100
  and length(email) between 5 and 160
  and length(objet) between 1 and 150
  and length(message) between 1 and 2000
);

drop policy if exists "buildream equipe lire demandes" on public.demandes_contact;
create policy "buildream equipe lire demandes"
on public.demandes_contact for select to authenticated
using (public.buildream_role_connecte() in ('admin','staff'));

drop policy if exists "buildream equipe traiter demandes" on public.demandes_contact;
create policy "buildream equipe traiter demandes"
on public.demandes_contact for update to authenticated
using (public.buildream_role_connecte() in ('admin','staff'))
with check (public.buildream_role_connecte() in ('admin','staff'));

-- 10) Droits d'accès API pour les rôles Supabase.
grant select on public.secteurs, public."matériels" to anon, authenticated;
grant insert, update, delete on public.secteurs, public."matériels" to authenticated;
grant select, insert, update on public.demandes_contact to anon, authenticated;
grant usage, select on sequence public.demandes_contact_identifiant_seq to anon, authenticated;
grant select, insert, update on public.profil to authenticated;


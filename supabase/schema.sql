-- BUILDREAM : adaptation à la structure anglaise existante

-- 1. Ajouter la visibilité des secteurs
ALTER TABLE public.sectors
ADD COLUMN IF NOT EXISTS is_active boolean
DEFAULT true;

-- 2. Créer la table des demandes de contact
CREATE TABLE IF NOT EXISTS public.contact_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL,
    subject text NOT NULL,
    message text NOT NULL,
    status text NOT NULL DEFAULT 'nouvelle',
    created_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Activer RLS
ALTER TABLE public.profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sectors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.materials ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_requests ENABLE ROW LEVEL SECURITY;

-- 4. Lecture publique des secteurs actifs
DROP POLICY IF EXISTS "public_read_sectors"
ON public.sectors;

CREATE POLICY "public_read_sectors"
ON public.sectors
FOR SELECT TO anon, authenticated
USING (is_active = true);

-- 5. Lecture publique des matériaux disponibles
DROP POLICY IF EXISTS "public_read_materials"
ON public.materials;

CREATE POLICY "public_read_materials"
ON public.materials
FOR SELECT TO anon, authenticated
USING (available = true);

-- 6. Envoi public des demandes
DROP POLICY IF EXISTS "public_insert_contact_requests"
ON public.contact_requests;

CREATE POLICY "public_insert_contact_requests"
ON public.contact_requests
FOR INSERT TO anon, authenticated
WITH CHECK (
    length(name) BETWEEN 1 AND 100
    AND length(email) BETWEEN 5 AND 160
    AND length(subject) BETWEEN 1 AND 150
    AND length(message) BETWEEN 1 AND 2000
);

-- 7. Droits de lecture et d'insertion
GRANT SELECT ON public.sectors, public.materials
TO anon, authenticated;

GRANT INSERT ON public.contact_requests
TO anon, authenticated;

GRANT USAGE, SELECT ON SEQUENCE
public.contact_requests_id_seq
TO anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.sectors, public.materials
TO authenticated;

GRANT SELECT, UPDATE
ON public.contact_requests
TO authenticated;
